"""Migrations and readiness against a real PostgreSQL (design D10)."""

import asyncio
from collections.abc import Callable
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from conftest import asyncpg_url
from fastapi.testclient import TestClient
from testcontainers.community.postgres import PostgresContainer

from parlora_server.config import Settings
from parlora_server.db import Database
from parlora_server.main import create_app

pytestmark = pytest.mark.integration

ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"


def alembic_config(url: str) -> Config:
    config = Config(ALEMBIC_INI)
    config.attributes["database_url"] = url
    config.attributes["configure_logging"] = False
    return config


def test_migrations_apply_and_match_the_models(postgres_url: str) -> None:
    config = alembic_config(postgres_url)

    command.upgrade(config, "head")
    # Raises AutogenerateDiffsDetected when the models and migrations disagree.
    command.check(config)
    command.downgrade(config, "base")


def test_database_answers_a_ping(postgres_url: str, make_settings: Callable[..., Settings]) -> None:
    database = Database(make_settings(database={"url": postgres_url}).database)

    async def ping_and_dispose() -> bool:
        try:
            return await database.ping()
        finally:
            await database.dispose()

    assert asyncio.run(ping_and_dispose()) is True


@pytest.mark.slow
def test_readiness_follows_the_database(
    disposable_postgres: PostgresContainer, make_settings: Callable[..., Settings]
) -> None:
    settings = make_settings(database={"url": asyncpg_url(disposable_postgres)})

    with TestClient(create_app(settings)) as client:
        up = client.get("/api/v1/health/ready")
        disposable_postgres.get_wrapped_container().stop(timeout=1)
        down = client.get("/api/v1/health/ready")

    assert up.status_code == 200
    assert up.json() == {"status": "ok", "checks": {"database": "ok"}}
    assert down.status_code == 503
    assert down.json()["checks"] == {"database": "unavailable"}
    assert disposable_postgres.password not in down.text
